/**
 * Convert full article into sanitized summary for client-side search indexing.
 */
export function summarizeManualArticle(article: ManualArticle): ManualArticleSummary {
  return {
    slug: article.slug,
    chapterId: article.chapterId,
    chapterTitle: article.chapterTitle,
    order: article.order,
    title: article.title,
    summary: article.summary,
    keywords: article.keywords,
    intendedRoles: article.intendedRoles,
    requiredPermission: article.requiredPermission,
    requiresMfa: article.requiresMfa,
    riskLevel: article.riskLevel,
    routes: article.routes,
    owner: article.owner,
    lastVerified: article.lastVerified,
    visualId: article.visualId,
  };
}

/**
 * Determine if a staff member can access a given article based on role and permissions.
 */
export function canStaffReadArticle(
  article: ManualArticle,
  role: StaffRole,
  active: boolean,
): boolean {
  if (!active) return false;
  if (role === 'super_admin') return true;

  // Check if role is explicitly in intended roles
  if (!article.intendedRoles.includes(role)) {
    return false;
  }

  // If article requires a specific mutating permission, check if staff holds it
  if (article.requiredPermission) {
    if (!staffCan({ role, active }, article.requiredPermission)) {
      // General read-only navigation guides remain accessible if role is intended
      if (article.riskLevel === 'production' && article.chapterId !== 'start' && article.chapterId !== 'security') {
        return false;
      }
    }
  }

  return true;
}

/**
 * Returns permitted chapters populated with summaries of permitted articles.
 */
export function getPermittedManualChapters(
  role: StaffRole,
  active: boolean,
): ManualChapter[] {
  if (!active) return [];

  const permittedArticles = MANUAL_ARTICLES.filter((art) =>
    canStaffReadArticle(art, role, active),
  );

  const chapters: ManualChapter[] = [];

  for (const def of MANUAL_CHAPTER_DEFS) {
    const chapterArticles = permittedArticles
      .filter((art) => art.chapterId === def.id)
      .sort((a, b) => a.order - b.order)
      .map(summarizeManualArticle);

    if (chapterArticles.length > 0) {
      chapters.push({
        ...def,
        articles: chapterArticles,
      });
    }
  }

  return chapters;
}

/**
 * Returns a single permitted full article, or null if unauthorized/not found.
 */
export function getPermittedManualArticle(
  slug: string,
  role: StaffRole,
  active: boolean,
): ManualArticle | null {
  if (!active) return null;
  const article = MANUAL_ARTICLES.find((a) => a.slug === slug);
  if (!article) return null;
  if (!canStaffReadArticle(article, role, active)) return null;
  return article;
}

/**
 * Returns sanitized summaries of all permitted articles for client-side search.
 */
export function getPermittedManualSummaries(
  role: StaffRole,
  active: boolean,
): ManualArticleSummary[] {
  if (!active) return [];
  return MANUAL_ARTICLES.filter((art) => canStaffReadArticle(art, role, active)).map(
    summarizeManualArticle,
  );
}

