// Bakes the social / review-platform brand marks into a static TS module, the
// same way scripts/build-service-icons.mjs bakes the trade glyphs. Re-run after
// editing MARKS:
//   node scripts/build-social-icons.mjs
//
// WHY BAKED AND NOT FETCHED. A published contractor site must not make a
// third-party request to render its own footer: it costs a DNS + TLS handshake
// on every page load, it hands a CDN a log of every visitor to every customer's
// site, and it is one more thing that can be down. Baking makes the icons part
// of our own bundle — no runtime Iconify dependency, no CDN, and only these ~15
// marks ship rather than all 3,726.
//
// @iconify-json/simple-icons is a devDependency for exactly this reason: it is a
// build-time source, never shipped or called at runtime.
//
// SOLID FILL, NOT STROKE. Simple Icons are single-path solid glyphs, unlike
// Lucide's stroke geometry — so every mark from that set is written with
// mode: 'fill'. Mixing the two without saying which is which paints a brand mark
// as an outline blob, which is how you get a Facebook logo nobody recognises.
import { getIconData } from '@iconify/utils';
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const simple = require('@iconify-json/simple-icons/icons.json');
const lucide = require('@iconify-json/lucide/icons.json');

// Platform id (stable — stored in site content, never rename) -> icon source.
// `set` picks which Iconify collection to read from.
//
// ANGI AND BBB HAVE NO BRAND MARK HERE ON PURPOSE. Simple Icons removed both
// after trademark requests, and hand-redrawing someone's registered logo to
// dodge that is worse than not having it. They get a meaningful Lucide glyph
// instead — a review star and an accreditation shield — which reads correctly in
// a row of links that are labelled anyway.
const MARKS = {
  facebook: { set: 'simple', name: 'facebook' },
  instagram: { set: 'simple', name: 'instagram' },
  youtube: { set: 'simple', name: 'youtube' },
  tiktok: { set: 'simple', name: 'tiktok' },
  linkedin: { set: 'simple', name: 'linkedin' },
  x: { set: 'simple', name: 'x' },
  pinterest: { set: 'simple', name: 'pinterest' },
  // Nextdoor's Simple Icons entry is a WORDMARK, not a symbol — 2.4KB of path
  // data spelling out "nextdoor" in lowercase. It renders as unreadable mush at
  // the 19px an icon row uses, which a screenshot caught and no measurement
  // would have: the link was present, correctly labelled, and the right size.
  // A house reads as a neighbourhood app and is legible at any size.
  nextdoor: { set: 'lucide', name: 'house' },
  yelp: { set: 'simple', name: 'yelp' },
  houzz: { set: 'simple', name: 'houzz' },
  thumbtack: { set: 'simple', name: 'thumbtack' },
  google: { set: 'simple', name: 'google' },
  angi: { set: 'lucide', name: 'star' },
  bbb: { set: 'lucide', name: 'shield-check' },
  website: { set: 'lucide', name: 'globe' },
};

// Same sanitizer as the service icons: strip per-element presentation attributes
// so the parent <svg> supplies the paint and `currentColor` tinting works for
// every consumer (footer, header bar, builder picker).
function sanitizeBody(body) {
  return body
    .replace(/\s+(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin|stroke-miterlimit|stroke-opacity|fill-opacity)="[^"]*"/g, '')
    .replace(/<g\s*>/g, '')
    .replace(/<\/g>/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

const out = {};
for (const [key, { set, name }] of Object.entries(MARKS)) {
  const collection = set === 'simple' ? simple : lucide;
  const data = getIconData(collection, name);
  // Unlike the trade glyphs, a missing mark here is fatal rather than skipped:
  // a trade with one fewer glyph option is a smaller picker, but a PLATFORM with
  // no icon is a blank gap in a published footer.
  if (!data || !data.body) {
    console.error(`Social mark "${key}" -> ${set}:${name} not found. Fix MARKS before regenerating.`);
    process.exit(1);
  }
  const body = sanitizeBody(data.body);
  if (body.includes('<g')) {
    console.error(`Social mark "${key}" (${set}:${name}) has a <g> that survived sanitizing — handle it before regenerating.`);
    process.exit(1);
  }
  out[key] = {
    body,
    width: data.width ?? collection.width ?? 24,
    height: data.height ?? collection.height ?? 24,
    // Simple Icons are solid; Lucide is stroke geometry.
    ...(set === 'simple' ? { mode: 'fill' } : {}),
  };
}

console.log('Resolved marks:', Object.keys(out).join(', '));

const banner =
  '// AUTO-GENERATED by scripts/build-social-icons.mjs — do not edit by hand.\n' +
  '// Sources: Simple Icons (@iconify-json/simple-icons, CC0) for the brand marks,\n' +
  '// Lucide (@iconify-json/lucide, MIT) for angi/bbb/website, which have no\n' +
  '// permissively-licensed brand mark. Re-run the script to refresh.\n' +
  "// mode 'fill' = solid-fill glyph (default is stroke).\n\n" +
  "export type SocialIconGlyph = { body: string; width: number; height: number; mode?: 'fill' };\n\n" +
  'export const SOCIAL_ICON_GLYPHS: Record<string, SocialIconGlyph> = {\n';

const lines = Object.entries(out).map(
  ([key, g]) => `  ${key}: { body: ${JSON.stringify(g.body)}, width: ${g.width}, height: ${g.height}${g.mode ? `, mode: ${JSON.stringify(g.mode)}` : ''} },`
);
const contents = banner + lines.join('\n') + '\n};\n';

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'templates', 'social-icons.data.ts');
writeFileSync(target, contents, 'utf8');
console.log(`Wrote ${Object.keys(out).length} marks to ${target}`);
