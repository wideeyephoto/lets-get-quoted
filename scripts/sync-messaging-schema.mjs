const START = '-- BEGIN GENERATED SIGNALWIRE MESSAGING AND VOICE RUNTIME';
const END = '-- END GENERATED SIGNALWIRE MESSAGING AND VOICE RUNTIME';

function lf(value) {
  return value.replace(/\r\n/g, '\n');
}

async function expectedBlock() {
  const sections = [];
  for (const migration of MIGRATIONS) {
    const body = lf(await readFile(resolve(ROOT, migration), 'utf8')).trim();
    sections.push(`-- Source: ${migration}\n${body}`);
  }
  return `${START}\n-- Generated by scripts/sync-messaging-schema.mjs. Do not edit this block by hand.\n\n${sections.join('\n\n')}\n${END}`;
}

function replaceBlock(schema, block) {
  const normalized = lf(schema);
  const start = normalized.indexOf(START);
  const end = normalized.indexOf(END);
  if ((start < 0) !== (end < 0) || (start >= 0 && end < start)) {
    throw new Error('schema.sql has an incomplete generated messaging block.');
  }
  if (start < 0) return `${normalized.trimEnd()}\n\n${block}\n`;
  const after = end + END.length;
  return `${normalized.slice(0, start).trimEnd()}\n\n${block}${normalized.slice(after)}`;
}

const mode = process.argv[2] ?? '--check';
if (mode !== '--check' && mode !== '--write') {
  throw new Error('Usage: node scripts/sync-messaging-schema.mjs [--check|--write]');
}

const schema = await readFile(SCHEMA, 'utf8');
const block = await expectedBlock();
const synchronized = replaceBlock(schema, block);
if (mode === '--write') {
  await writeFile(SCHEMA, synchronized, 'utf8');
  console.log(`Synchronized ${MIGRATIONS.length} runtime migrations into schema.sql.`);
} else if (lf(schema) !== synchronized) {
  console.error('schema.sql is missing or has drifted from the generated messaging runtime block.');
  console.error('Run: node scripts/sync-messaging-schema.mjs --write');
  process.exitCode = 1;
} else {
  console.log(`schema.sql exactly mirrors ${MIGRATIONS.length} runtime migrations.`);
}
